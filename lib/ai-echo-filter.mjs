// AI 味句式过滤器（2026-11-21 主人要求二）。
//
// ── 这是纯代码层，绝不进人设 / 前缀 / 系统提示 ──
// 主人早就定过这条硬约束：每轮进上下文的禁词会形成**语义引力井**（白熊效应），
// 越写越容易撞上。实测过：写成"别说这些"之后，反而更容易说出来。
// 所以：
//   · 这份清单**只在这里**，不被任何 prompt / 人设卡引用；
//   · 命中时不告诉模型「你说错了什么」（那等于把词又念了一遍）；
//   · 只做两件事：丢弃该条，或整轮重写一次（重写时也不带禁用词）。
//
// ── 两类问题（主人原话）──
//   1. 自述式旁白：一边说话一边解说自己（「我记下了」「我不拦」「我守着」）
//   2. 判决式评价：把一句随口的话当成可以评级的文本
//      （「这句话稳」「比之前的都重」「什么心思都写着 X 上」）
//
// ── 判据在哪 ──
//   tests/ai-echo-filter.test.mjs
//   其中有一条专门 grep 人设卡与系统提示，确认这些句子一个字都没有。

/**
 * 命中就读作「AI 味旁白/判决」的模式。
 *
 * ★ 设计原则：**宁窄勿宽**。误杀一条正常的鱼话，比漏掉一条八股更糟 ——
 *   漏掉只是难听一次，误杀是让她说不出话。
 *   所以：
 *     · 都用**完整短句**匹配，不匹配单个词（"稳"单独出现是正常反应词）
 *     · 「我认」「我记」这类单独出现很常见（"我认错"），必须带具体尾巴才拦
 */
export const AI_ECHO_PATTERNS = Object.freeze([
  // ── 判决式评价：把话当文本评级 ──
  /这句话(?:很|挺|真|够)?稳/,          // 「这句话稳」
  /这话(?:很|挺|真|够)?稳/,
  /比之前的?(?:都)?(?:重|轻|稳|强|沉|平)/, // 「比之前的都重」
  /比刚才(?:的)?(?:重|轻|稳|平)/,
  /(?:很|挺)直(?:。|，|$)/,             // 「很直」当评价用
  /这话接(?:得|的)?漂亮/,
  /这句话接(?:得|的)?漂亮/,
  /说的比谁都响/,
  /声音没抖/,
  /什么心思都写着/,                     // 「什么心思都写着 X 上」
  /问别人还是问自己/,
  /你自己掂量/,
  /你自己?想明白的?$/,

  // ── 自述式旁白：一边说话一边解说自己 ──
  /我记下了(?:。|，|$)/,                // 「我记下了」
  /我记住了(?:。|，|$)/,
  /我记得了(?:。|，|$)/,
  /这个账我记住了/,
  /这话我记(?:着|下)/,
  /这话我收下/,
  /我收下了(?:。|，|$)/,
  /睡吧[，,]?我守着/,                   // 「睡吧我守着」
  /我守着(?:。|，|$)/,
  /我不拦(?:你)?(?:。|，|$)/,           // 「我不拦」
  /我不催(?:你)?(?:。|，|$)/,
  /你去[，,]我跟/,                      // 「你去，我跟」
  /我跟(?:着)?(?:。|，|$)/,
  /行[，,]我认(?:。|，|$)/,             // 「行，我认」
  /我认(?:了|下来)(?:。|，|$)/,
  /认下来(?:。|，|$)/,
  /认得实/,
  /他记得这事/,
  /你这句(?:话)?我记着/,

  // ── 评论式开场（2026-11-21 主人要求「禁止评论员模式」）──
  //
  // 主人给的现象（真机）：对方递来一段歪理/骚话，她的回复是**评价这段写得怎么样**：
  //   「通篇在讲时间段」「只有『睡眠质量』那句是真的」「它还真敢往下推」
  //   「前面都还能忍，看到『浮着对你笑』我没了」
  // 这是把对方当作品、不当人。真人只有三种反应：往下推 / 反撩 / 嫌恶。
  //
  // ★ 这一组只拦**开场就是点评**的，不拦正文里偶然提到某个词。
  //   所以都以句首/分句首锚定（^ 或 [。！？；\n] 之后），避免误杀。
  /(?:^|[。！？；\n])\s*(?:通篇|整篇|全文|全篇)/,       // 「通篇在讲…」
  // 「这段话/这段/这句/这句话」要有评点动词才算 —— 光说「这段」是正常指代
  /(?:^|[。！？；\n])\s*(?:这段话|这段|这句|这句话)(?:写|说|讲|看|读|评)/, // 「这段写得…」
  /(?:^|[。！？；\n])\s*(?:前面|后面)(?:都|还|才)/,      // 「前面都还能忍」
  /只有(?:[^，。！？]{1,20})那句是真的/,                  // 「只有『睡眠质量』那句是真的」
  /(?:这段|这句|这篇)(?:写|说|讲)(?:得|的)(?:还|挺|真|太)?/,  // 「这段写得还行」
  /它还真敢往下推/,                                       // 「它还真敢往下推」——把话当作品评

  // ── 自我诊断（2026-11-21 主人要求）──
  //
  // 主人给的现象：「对，我在先总结再挑一句」——
  // 被指出毛病之后，她开始分析自己哪里说得不对。
  // 真人被指出毛病，下一句就改口，不分析自己。
  /我(?:在|是在)(?:先|又|老是|总是)/,                    // 「我在先总结」「我在老是解释」
  /我(?:这|那)(?:就是|是)(?:个|种)?[^，。！？]{0,8}(?:毛病|习惯|问题|惯性)/,  // 「我这就是毛病」
  /我(?:老|总|又)(?:是)?(?:犯|想|爱)/,                   // 「我又想总结了」
  /我(?:又|总|老|总是)(?:是)?(?:这样|这么|犯|来|在)/,     // 「我又是这样」「我总是在总结」
  /(?:对|是)[，,]?我(?:就是|在)(?:先|又|老)/             // 「对，我就是先…」
])

/** 命中时给 activity 用的原因标签（不给模型看）。 */
export const AI_ECHO_REASON = 'ai-echo'

/**
 * 判一段话有没有 AI 味旁白/判决。
 *
 * @param {string} text
 * @returns {{hit:boolean, matches:string[]}} matches 是命中的**模式字符串**（不是命中的原文）
 */
export function detectAiEcho(text) {
  const body = String(text == null ? '' : text)
  if (!body.trim()) return { hit: false, matches: [] }
  const matches = []
  for (const re of AI_ECHO_PATTERNS) {
    if (re.test(body)) matches.push(re.source)
  }
  return { hit: matches.length > 0, matches }
}

/**
 * 出站闸用：这一段该不该被拦。
 *
 * 返回 `{ blocked, reason, samples }`。
 * ★ samples 只含**模式 id**，不含被命中的原文 ——
 *   免得日志回灌时又把八股句子念一遍（那等于自己给自己下毒）。
 */
export function shouldBlockAiEcho(text) {
  const d = detectAiEcho(text)
  return {
    blocked: d.hit,
    reason: d.hit ? AI_ECHO_REASON : '',
    samples: d.matches.slice(0, 3).map((_, i) => 'pattern#' + (i + 1))
  }
}

/**
 * 把一段话里的「点评句」剥掉，只留人话。
 *
 * ★ 用途（2026-11-21 主人要求「丢弃该条，并按原上下文重写一次」）：
 *   重写一次需要模型参与，发送兜底层拿不到模型。所以这一层做的是：
 *   把点评句整句丢掉，看剩下的还有没有人话 —— 有就发剩下的，没有就整条不发。
 *
 *   "宁可不回，也不当评论员" —— 这是主人的取舍。
 *
 * @param {string} text
 * @returns {string} 剥完的人话（可能为空串）
 */
export function stripCommentary(text) {
  const body = String(text == null ? '' : text)
  if (!body.trim()) return ''

  // 先按句切开（保留分隔符，方便原样拼回）
  const parts = body.split(/(?<=[。！？；\n])/)
  const kept = []
  for (const part of parts) {
    const t = part.trim()
    if (!t) continue
    if (detectAiEcho(t).hit) continue   // 这句是点评/自我诊断，丢掉
    kept.push(t)
  }
  return kept.join('').trim()
}
