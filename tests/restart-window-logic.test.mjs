// 复刻桥里的豁免判定，用真实场景验「08:47 那条 27 分钟前的消息」现在会怎样。
// ★ 这不是测桥本身（那要重启），是测**我写的那段逻辑**对不对。
import { test } from 'node:test'
import assert from 'node:assert/strict'

/** 照搬 host.js 里的判定逻辑（改动后）。 */
export function judge({ 消息秒, 桥活于秒, 现在秒, 基础窗口分 = 10, 重启豁免分 = 30 }) {
  const 年龄秒 = 消息秒 > 0 ? 现在秒 - 消息秒 : 0
  const 落在重启窗口 = 消息秒 > 0 && 消息秒 < 桥活于秒 && (桥活于秒 - 消息秒) <= 重启豁免分 * 60
  const 用窗口秒 = (落在重启窗口 ? 重启豁免分 : 基础窗口分) * 60
  const 太旧 = 消息秒 > 0 && 年龄秒 > 用窗口秒
  return { 落在重启窗口, 用窗口秒: 用窗口秒 / 60, 太旧, 年龄秒: Math.round(年龄秒 / 60) }
}

// 现场：09:13 重启，09:14:07 判定，主人 08:47 发的消息
const 桥活于 = new Date('2026-11-20T09:13:00+08:00').getTime() / 1000
const 判定于 = new Date('2026-11-20T09:14:07+08:00').getTime() / 1000
const 消息于 = new Date('2026-11-20T08:47:00+08:00').getTime() / 1000

test('现场复现：08:47 那条 27 分钟前的，现在不该被丢', () => {
  const r = judge({ 消息秒: 消息于, 桥活于秒: 桥活于, 现在秒: 判定于 })
  assert.equal(r.落在重启窗口, true, '★ 该判成「落在重启窗口」—— 那是我方没在线')
  assert.equal(r.用窗口秒, 30, '窗口放宽到 30 分钟')
  assert.equal(r.太旧, false, '★ 27 分钟 < 30 分钟 ⇒ 不丢，进入正常补投')
})

test('对照：旧逻辑（没有豁免）会丢掉它', () => {
  // 旧逻辑：窗口固定 10 分钟
  const 年龄分 = Math.round((判定于 - 消息于) / 60)
  const 旧太旧 = 年龄分 > 10
  assert.equal(旧太旧, true, `旧逻辑 27 > 10 分钟 ⇒ 丢弃（这就是主人看到的现象）`)
})

test('正常运行时窗口仍是 10 分钟（不许被顺手放大）', () => {
  // 消息在桥活着之后来的（不是重启期间），4 小时前
  const 老消息 = 桥活于 + 3600
  const r = judge({ 消息秒: 老消息, 桥活于秒: 桥活于, 现在秒: 桥活于 + 4 * 3600 })
  assert.equal(r.落在重启窗口, false, '桥活着之后来的，不算重启窗口')
  assert.equal(r.用窗口秒, 10, '窗口仍是 10 分钟')
  assert.equal(r.太旧, true, '4 小时前的照常丢（那是真旧消息）')
})

test('边界：正好 30 分钟 → 不丢', () => {
  const 消息 = 桥活于 - 30 * 60
  const r = judge({ 消息秒: 消息, 桥活于秒: 桥活于, 现在秒: 桥活于 })
  assert.equal(r.落在重启窗口, true)
  assert.equal(r.太旧, false, '30*60 <= 30*60，边界含等号')
})

test('边界：31 分钟 → 丢（超出豁免）', () => {
  const 消息 = 桥活于 - 31 * 60
  const r = judge({ 消息秒: 消息, 桥活于秒: 桥活于, 现在秒: 桥活于 })
  assert.equal(r.落在重启窗口, false, '超过 30 分钟不算重启窗口')
  assert.equal(r.太旧, true)
})

test('重启后很久才判定：豁免仍按「距桥活过来」算，不按年龄', () => {
  // 09:13 活过来，11:00 才判定（1 小时 47 分后）
  // 消息是 08:47 发的 —— 距桥活过来 26 分钟 ⇒ 仍在豁免窗口内
  const 很久后 = 桥活于 + 107 * 60
  const r = judge({ 消息秒: 消息于, 桥活于秒: 桥活于, 现在秒: 很久后 })
  assert.equal(r.落在重启窗口, true, '★ 判据是「距桥活过来多久」，不是「消息多老」')
  assert.equal(r.用窗口秒, 30)
  // 但年龄已经 133 分钟，超过 30 分钟窗口 ⇒ 会丢
  assert.equal(r.太旧, true, '年龄超窗口还是会丢（豁免不是无限期）')
})

test('消息时间缺失（0）→ 不按旧消息处理', () => {
  const r = judge({ 消息秒: 0, 桥活于秒: 桥活于, 现在秒: 判定于 })
  assert.equal(r.落在重启窗口, false)
  assert.equal(r.太旧, false, '没有时间戳就不判"旧"')
})
